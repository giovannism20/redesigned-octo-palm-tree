package com.giovannimartins.rreader.tts.neural

import android.content.Context
import android.util.Log
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.filters.LargeTest
import androidx.test.platform.app.InstrumentationRegistry
import com.k2fsa.sherpa.onnx.GenerationConfig
import com.k2fsa.sherpa.onnx.OfflineTts
import com.k2fsa.sherpa.onnx.OfflineTtsConfig
import com.k2fsa.sherpa.onnx.OfflineTtsKokoroModelConfig
import com.k2fsa.sherpa.onnx.OfflineTtsModelConfig
import com.k2fsa.sherpa.onnx.OfflineTtsVitsModelConfig
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.runBlocking
import org.junit.Assume.assumeTrue
import org.junit.Test
import org.junit.runner.RunWith
import java.io.File
import kotlin.system.measureNanoTime

/**
 * How fast the installed neural voices render on this phone, to tune listening above 1.0×. Not a pass/fail test: it
 * logs, under the tag [TAG], for each installed package, thread count and generation speed, the render time divided
 * by the time the passage takes to hear at 1.25× ("listen ratio"; above 1.0 the player starves). Speed 1.0 is heard
 * through the player's time-stretch at 1.25×; speed 1.25 is generated by the model and heard at 1.0×.
 *
 * Run it alone on the phone (it takes a few minutes, keep the screen on and the phone cool):
 * `adb shell am instrument -w -e class com.giovannimartins.rreader.tts.neural.NeuralSpeedBenchmark
 * com.giovanni_martins.rreader.test/androidx.test.runner.AndroidJUnitRunner`, then `adb logcat -d -s RReaderSpeed`.
 * Options (`-e name value`): `threads` (for example `4,8`), `speeds` (for example `1.25`) and `only` (package ids,
 * for example `kokoro,kokoro-fp32`). A full-precision Kokoro model copied to `files/bench/kokoro-fp32/model.onnx`
 * is measured as `kokoro-fp32`, with the installed Kokoro package's voices and tokens.
 */
@LargeTest
@RunWith(AndroidJUnit4::class)
class NeuralSpeedBenchmark {
    private val context: Context = ApplicationProvider.getApplicationContext()
    private val store = VoicePackageStore(context, Dispatchers.IO)
    private val runtime = SherpaOnnxRuntime(context)

    @Test
    fun logsRenderSpeedOfInstalledVoices() {
        val installed = runBlocking { store.installedNow() }
        val voices = NeuralVoices.all.filter { it.pkg.id in installed }.distinctBy { it.pkg }
        assumeTrue("no neural voice installed", voices.isNotEmpty())
        val phonemes = runtime.phonemize(PASSAGE)
        val cores = Runtime.getRuntime().availableProcessors()
        Log.i(TAG, "cores=$cores passage=${PASSAGE.length} chars")
        val candidates =
            voices.map { Candidate(it.pkg.id, it, File(store.directory(it.pkg), "model.onnx")) } + fullPrecisionKokoro()
        val only = argument("only")?.split(',')
        candidates.filter { only == null || it.label in only }.forEach { candidate ->
            val sentences =
                phonemes
                    .map { if (candidate.voice.pkg.family == ModelFamily.KOKORO) KokoroPhonemes.fold(it) else it }
                    .filter(IntArray::isNotEmpty)
                    .toTypedArray()
            numbers("threads", THREADS.map(Int::toFloat)).map(Float::toInt).filter { it <= cores }.forEach { threads ->
                val tts = load(candidate, threads)
                try {
                    numbers("speeds", SPEEDS).forEach { speed -> measure(tts, candidate, sentences, threads, speed) }
                } finally {
                    tts.release()
                }
            }
        }
    }

    /** The installed Kokoro voice with a full-precision model copied in for comparison, when there is one. */
    private fun fullPrecisionKokoro(): List<Candidate> {
        val model = File(context.filesDir, "bench/kokoro-fp32/model.onnx")
        val dora = NeuralVoices.all.first { it.pkg.family == ModelFamily.KOKORO }
        return if (model.isFile &&
            store.isComplete(dora.pkg)
        ) {
            listOf(Candidate("kokoro-fp32", dora, model))
        } else {
            emptyList()
        }
    }

    private fun argument(name: String): String? = InstrumentationRegistry.getArguments().getString(name)

    private fun numbers(
        name: String,
        default: List<Float>,
    ): List<Float> = argument(name)?.split(',')?.map(String::toFloat) ?: default

    private class Candidate(
        val label: String,
        val voice: NeuralVoice,
        val model: File,
    )

    private fun measure(
        tts: OfflineTts,
        candidate: Candidate,
        sentences: Array<IntArray>,
        threads: Int,
        speed: Float,
    ) {
        val config =
            GenerationConfig(
                silenceScale = 1f,
                speed = speed,
                sid = candidate.voice.speakerId,
                phonemeCodepoints = sentences,
            )
        tts.generateWithConfig("", config) // Warm-up: the first run allocates.
        var samples = 0
        val nanos = (1..RUNS).sumOf { measureNanoTime { samples = tts.generateWithConfig("", config).samples.size } }
        val renderSeconds = nanos / NANOS_PER_SECOND / RUNS
        val audioSeconds = samples.toDouble() / tts.sampleRate()
        val listenSeconds = if (speed == 1f) audioSeconds / LISTEN_SPEED else audioSeconds
        Log.i(
            TAG,
            "%s threads=%d speed=%.2f render=%.2fs audio=%.2fs rtf=%.2f listen-ratio@1.25=%.2f".format(
                candidate.label,
                threads,
                speed,
                renderSeconds,
                audioSeconds,
                renderSeconds / audioSeconds,
                renderSeconds / listenSeconds,
            ),
        )
    }

    private fun load(
        candidate: Candidate,
        threads: Int,
    ): OfflineTts {
        val pkg = candidate.voice.pkg
        val directory = store.directory(pkg)
        val model = candidate.model.path
        val tokens = File(directory, "tokens.txt").path
        val models =
            when (pkg.family) {
                ModelFamily.KOKORO -> {
                    OfflineTtsModelConfig(
                        kokoro =
                            OfflineTtsKokoroModelConfig(
                                model = model,
                                voices = File(directory, "voices.bin").path,
                                tokens = tokens,
                                lang = "pt-br",
                            ),
                        numThreads = threads,
                        provider = "cpu",
                    )
                }

                ModelFamily.PIPER -> {
                    OfflineTtsModelConfig(
                        vits = OfflineTtsVitsModelConfig(model = model, tokens = tokens),
                        numThreads = threads,
                        provider = "cpu",
                    )
                }
            }
        return OfflineTts(null, OfflineTtsConfig(model = models, maxNumSentences = 1, silenceScale = 1f))
    }

    private companion object {
        const val TAG = "RReaderSpeed"
        const val RUNS = 2
        const val LISTEN_SPEED = 1.25
        const val NANOS_PER_SECOND = 1e9
        val THREADS = listOf(2, 4, 6, 8)
        val SPEEDS = listOf(1f, 1.25f)

        /** About 20 seconds of narration, in the length range of the app's segments. */
        const val PASSAGE =
            "Uma noite destas, vindo da cidade para o Engenho Novo, encontrei no trem da Central um rapaz aqui do " +
                "bairro, que eu conheço de vista e de chapéu. Cumprimentou-me, sentou-se ao pé de mim, falou da lua " +
                "e dos ministros, e acabou recitando-me versos. A viagem era curta, e os versos pode ser que não " +
                "fossem inteiramente maus."
    }
}
